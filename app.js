// ---- State ---------------------------------------------------------------
let lang = "cy";
const history = []; // {role, content}
const $ = (s) => document.querySelector(s);
const log = $("#log"), form = $("#form"), q = $("#q"), send = $("#send"), sugg = $("#suggestions");

function setLang(next) {
  lang = next;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = T[lang][el.dataset.i18n]));
  q.placeholder = T[lang].placeholder;
  document.querySelectorAll(".lang button").forEach((b) => b.setAttribute("aria-pressed", b.dataset.lang === lang));
  renderSuggestions();
}

function renderSuggestions() {
  sugg.replaceChildren();
  if (history.length) return; // hide once the chat has started
  T[lang].suggestions.forEach((text) => {
    const b = document.createElement("button");
    b.type = "button";
    b.textContent = text;
    b.onclick = () => ask(text);
    sugg.appendChild(b);
  });
}

function addMsg(text, cls) {
  const div = document.createElement("div");
  div.className = "msg " + cls;
  div.textContent = text;
  log.appendChild(div);
  log.scrollTop = log.scrollHeight;
  return div;
}

async function ask(text) {
  text = text.trim();
  if (!text || send.disabled) return;
  addMsg(text, "user");
  history.push({ role: "user", content: text });
  renderSuggestions();
  q.value = "";
  send.disabled = true;
  const pending = addMsg(T[lang].thinking, "bot thinking");

  try {
    const res = await fetch(API_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ messages: history.slice(-10), lang }),
    });
    const data = await res.json();
    if (!res.ok || !data.reply) throw new Error(data.error || res.status);
    pending.className = "msg bot";
    pending.textContent = data.reply;
    history.push({ role: "assistant", content: data.reply });
  } catch (e) {
    console.error(e);
    pending.className = "msg bot error";
    pending.textContent = T[lang].error;
    history.pop(); // drop the unanswered question so the next try is clean
  } finally {
    send.disabled = false;
    q.focus();
    log.scrollTop = log.scrollHeight;
  }
}

form.addEventListener("submit", (e) => { e.preventDefault(); ask(q.value); });
q.addEventListener("keydown", (e) => {
  if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); ask(q.value); }
});
q.addEventListener("input", () => { q.style.height = "auto"; q.style.height = q.scrollHeight + "px"; });
document.querySelectorAll(".lang button").forEach((b) => (b.onclick = () => setLang(b.dataset.lang)));

